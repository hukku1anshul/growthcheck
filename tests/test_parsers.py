"""Parser tests against real archived pages.

    python tests/test_parsers.py

WHY THESE EXIST
---------------
37% of claims in the store were parsed heuristically out of summary tables and
free text. Nothing checked that the parser read them correctly, and the first
thing a careful read of four pages turned up was that 250 of 544 Indian MPs were
silently missing their declared criminal-case count: the "Crime-O-Meter" block
writes the number AFTER the words ("Number of Criminal Cases: 88") and the regex
only matched a leading-number form that never appears on the page. Members with
zero cases parsed fine; every member WITH cases recorded no data at all.

That is the worst possible direction for an error in a tool like this - it made
the dataset look cleaner than reality - and it survived a full 543-member harvest
without a single visible symptom.

THE RULE FOR THIS FILE
----------------------
Expected values are read BY EYE from the rendered page and written down here by
hand. They are never generated by running the parser. A test whose expectations
came from the code under test proves only that the code is deterministic.

Each fixture is a real archived document, byte-identical to what the harvester
saw, so these tests also pin the page layouts we depend on: if MyNeta restructures
its pages, a fresh fixture will fail against these hand-read values and tell us.
"""

